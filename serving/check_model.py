"""Contract test for a model package.  Usage:  python -m serving.check_model serving.model_api:load_stub [artifact_dir]

Checks: protocols implemented, output shapes and dtypes, finite values, std > 0, latency per call, and that
the friction estimator moves toward the truth when fed measurements generated by the surrogate itself.
"""
from __future__ import annotations

import importlib
import sys
import time

import numpy as np

from serving.model_api import FEATURES, FrictionEstimator, Surrogate


def main(argv=None):
    argv = argv or sys.argv[1:]
    mod, fn = argv[0].split(":")
    art = argv[1] if len(argv) > 1 else None
    surrogate, estimator = getattr(importlib.import_module(mod), fn)(art)
    assert isinstance(surrogate, Surrogate), "surrogate does not implement Surrogate"
    assert isinstance(estimator, FrictionEstimator), "estimator does not implement FrictionEstimator"

    X = np.array([[2.0, 2 / 3, mf, 0.15, 0.3] for mf in (0.05, 0.2, 0.4, 0.8)])
    assert X.shape[1] == len(FEATURES)
    t0 = time.perf_counter()
    mu, sd = surrogate.predict(X)
    dt = (time.perf_counter() - t0) * 1000
    assert mu.shape == (4,) and sd.shape == (4,), "predict must return two arrays of shape (n,)"
    assert np.all(np.isfinite(mu)) and np.all(sd > 0), "non-finite mean or non-positive std"
    assert mu[0] > mu[-1], "inner-diameter change must fall with friction"

    truth = 0.3
    ring = dict(od_id=2.0, h_id=2 / 3, m=0.15)
    y_true = surrogate.predict(np.array([[2.0, 2 / 3, truth, 0.15, 0.3]]))[0][0]
    for _ in range(5):
        estimator.update(ring, 0.3, float(y_true), 0.3)
    m, s = estimator.mean_std()
    assert abs(m - truth) < 0.1, f"friction estimate {m:.3f} not near {truth}"
    print(f"OK  {surrogate.name} v{surrogate.version}: predict 4 rows in {dt:.2f} ms; "
          f"friction estimate {m:.3f} ± {s:.3f} (truth {truth})")


if __name__ == "__main__":
    main()
